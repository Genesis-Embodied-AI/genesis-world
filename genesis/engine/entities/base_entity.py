from dataclasses import dataclass
from typing import TYPE_CHECKING

import numpy as np
import torch

import genesis as gs
from genesis.engine.materials.base import Material
from genesis.options.morphs import Morph
from genesis.repr_base import RBC

if TYPE_CHECKING:
    from genesis.engine.scene import Scene
    from genesis.engine.sensors.base_sensor import Sensor


@dataclass
class EntityDescription:
    """Base class of what one entity of a scene is created from, whatever the solver simulating it.

    A scene names every entity it holds as one of these, so a kind of entity described later stands there too. The
    material is what every description holds, since the simulator picks the solver from it.
    """

    material: Material


class Entity(RBC):
    """
    Base class for all types of entities.
    """

    def __init__(
        self,
        idx,
        scene,
        morph,
        solver,
        material,
        surface,
        name: str | None = None,
    ):
        # An entity is created from one morph. A kind of entity built from several passes the primary one here.
        if not isinstance(morph, Morph):
            gs.raise_exception(f"An entity is created from one morph, got {type(morph).__name__}.")
        uid = gs.UID()
        while any(entity.uid.match(uid, short_only=True) for entity in scene.entities):
            uid = gs.UID()
        self._uid = uid
        self._idx = idx
        self._scene: "Scene" = scene
        self._solver = solver
        self._material = material
        self._morph = morph
        self._surface = surface
        self._sim = scene.sim

        # Set entity name (auto-generate if not provided)
        existing_names = {entity.name for entity in scene.entities if entity.name is not None}
        if name is not None:
            if name in existing_names:
                gs.raise_exception(f"Entity name '{name}' already exists in scene.")
            self._name = name
        else:
            morph_name = self._get_morph_identifier()
            self._name = f"{morph_name}_{uid.short()}"

        # The name is the handle 'scene.get_entity' resolves, and the name generated by default embeds the uid.
        gs.logger.info(
            f"Adding ~<{self.__repr_name__()}>~ ~~<{self._name}>~~. idx: ~<{self._idx}>~, "
            f"morph: ~<{morph}>~, material: ~<{self._material}>~."
        )

    # ------------------------------------------------------------------------------------
    # ----------------------------------- properties -------------------------------------
    # ------------------------------------------------------------------------------------

    @property
    def uid(self):
        return self._uid

    @property
    def idx(self):
        return self._idx

    @property
    def scene(self):
        return self._scene

    @property
    def sim(self):
        return self._sim

    @property
    def solver(self):
        return self._solver

    @property
    def surface(self):
        return self._surface

    @property
    def morph(self):
        return self._morph

    @property
    def desc(self) -> EntityDescription | None:
        """The description this entity was created from, or None for a kind of entity no description carries.

        'Scene.export' writes every entity as its description and rejects a scene holding an entity without one. A
        kind of entity gains export support by returning its description here.
        """
        return None

    @property
    def material(self):
        return self._material

    @property
    def is_built(self):
        return self._solver._scene._is_built

    def _repr_brief(self):
        return f"{self.__repr_name__()}, idx: {self.idx}, morph: {self._repr_morph()}, material: {self.material}"

    def _repr_morph(self):
        return f"{self.morph}"

    @property
    def name(self) -> str:
        """
        The name of this entity.

        Returns
        -------
        str
            The entity's name. If a user-specified name was provided during creation,
            that name is returned. Otherwise, an auto-generated name based on the
            morph type and UID is returned.
        """
        return self._name

    @property
    def sensors(self) -> "gs.List[Sensor]":
        """List of sensors attached to this entity."""
        return self._sim._sensor_manager.get_sensors_by_entity(self._idx)

    @gs.assert_built
    def read_sensors(self, envs_idx=None) -> "dict[type[Sensor], torch.Tensor]":
        """
        Read every sensor attached to this entity as a tensor per sensor class.

        Always returns a fresh tensor independent of the internal sensor storage; the caller is free to mutate the
        result.

        Parameters
        ----------
        envs_idx : array-like | int | slice | None
            Environment selection. Defaults to all environments.

        Returns
        -------
        dict[Type[Sensor], torch.Tensor]
            For each sensor class with at least one sensor on this entity, a tensor of shape
            (B, [history,] entity_cache_size_for_class).
        """
        return self._sim._sensor_manager.read_sensors(entity_idx=self._idx, envs_idx=envs_idx)

    def _get_global_idx(self, idx_local, idx_local_max, idx_global_start=0, *, unsafe=False, batched_idx=False):
        if idx_local is None:
            idx_global = range(idx_global_start, idx_local_max + idx_global_start)
        elif isinstance(idx_local, (int, np.integer)):
            if idx_local < 0:
                idx_local = idx_local_max + idx_local
            idx_global = (idx_local + idx_global_start,)
        elif isinstance(idx_local, slice):
            start, stop, step = idx_local.indices(idx_local_max)
            idx_global = range(start + idx_global_start, stop + idx_global_start, step)
            if step < 0:
                idx_global = tuple(idx_global)
        elif isinstance(idx_local, range):
            if idx_local and -idx_local_max <= idx_local[0] < 0 and -idx_local_max <= idx_local[-1] < 0:
                # Every entry shifts by the same amount, so the constant step and the range form are preserved
                idx_global = range(
                    idx_local.start + idx_local_max + idx_global_start,
                    idx_local.stop + idx_local_max + idx_global_start,
                    idx_local.step,
                )
            elif idx_local and (idx_local[0] < 0 or idx_local[-1] < 0):
                # Mixed-sign entries wrap by different amounts, which breaks the constant step
                idx_global = [
                    i + idx_global_start + (idx_local_max if -idx_local_max <= i < 0 else 0) for i in idx_local
                ]
            else:
                idx_global = range(
                    idx_local.start + idx_global_start, idx_local.stop + idx_global_start, idx_local.step
                )
            if isinstance(idx_global, range) and idx_global.step < 0:
                idx_global = tuple(idx_global)
        elif isinstance(idx_local, (list, tuple)) and not (batched_idx and np.ndim(idx_local) == 2):
            try:
                idx_global = [
                    i + idx_global_start + (idx_local_max if -idx_local_max <= i < 0 else 0) for i in idx_local
                ]
            except TypeError:
                gs.raise_exception("Expecting a sequence of integers for `idx_local`.")
        else:
            if isinstance(idx_local, (list, tuple)):
                idx_local = np.asarray(idx_local)
            if isinstance(idx_local, torch.Tensor):
                if idx_local.dtype == torch.bool:
                    if idx_local.shape != (idx_local_max,):
                        gs.raise_exception(f"Boolean masks for `idx_local` must have shape ({idx_local_max},).")
                    idx_local, *_ = torch.where(idx_local)
                    is_negative_wrap_required = False
                else:
                    is_negative_wrap_required = idx_local.dtype.is_signed
                    where = torch.where
            elif isinstance(idx_local, np.ndarray):
                if np.issubdtype(idx_local.dtype, np.bool_):
                    if idx_local.shape != (idx_local_max,):
                        gs.raise_exception(f"Boolean masks for `idx_local` must have shape ({idx_local_max},).")
                    idx_local, *_ = np.where(idx_local)
                    is_negative_wrap_required = False
                else:
                    is_negative_wrap_required = not np.issubdtype(idx_local.dtype, np.unsignedinteger)
                    where = np.where
            else:
                gs.raise_exception("Expecting integer indices for `idx_local`.")
            if is_negative_wrap_required:
                # Wrap valid Python-style negatives before the global offset so those entries stay local to the entity
                is_valid_negative = (-idx_local_max <= idx_local) & (idx_local < 0)
                idx_local = where(is_valid_negative, idx_local + idx_local_max, idx_local)
            # Increment may be slow when dealing with heterogenuous data, so it must be avoided if possible
            if idx_global_start > 0:
                idx_global = idx_local + idx_global_start
            else:
                idx_global = idx_local

        # Early return if unsafe
        if unsafe:
            return idx_global

        # Perform a bunch of sanity checks
        idx_global = torch.as_tensor(idx_global, dtype=gs.tc_int, device=gs.device).contiguous()
        ndim = idx_global.ndim
        if ndim == 0:
            idx_global = idx_global[None]
        elif ndim > 1:
            gs.raise_exception("Expecting a 1D tensor for local index.")

        # FIXME: This check is too expensive
        # if (idx_global < 0).any() or (idx_global >= idx_global_start + idx_local_max).any():
        #     gs.raise_exception("`idx_local` exceeds valid range.")

        return idx_global

    # ------------------------------------------------------------------------------------
    # --------------------------------- naming methods -----------------------------------
    # ------------------------------------------------------------------------------------

    def _get_morph_identifier(self) -> str:
        """
        Get the identifier string from the morph for name generation.

        Must be overridden in subclasses to provide type-specific identifiers.
        """
        raise NotImplementedError
